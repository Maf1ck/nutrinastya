export function formatDate(iso: string): string {
  return new Date(`${iso}T12:00:00Z`).toLocaleDateString('uk-UA', { day: 'numeric', month: 'long', year: 'numeric' })
}

function articleText(a: Article): string {
  return [a.lead, ...a.takeaways, ...a.sections.flatMap((s) => [s.heading, ...(s.paragraphs ?? []), ...(s.list ?? []), s.tip ?? '']), ...(a.faq ?? []).flatMap((f) => [f.q, f.a])].join(' ')
}

/** хвилин читання при ~180 словах за хвилину */
export function readingMinutes(a: Article): number {
  return Math.max(1, Math.round(articleText(a).split(/\s+/).length / 180))
}

/** схожі статті: спершу з тієї ж категорії, потім найновіші */
export function relatedArticles(a: Article, count = 3): Article[] {
  const others = ARTICLES_SORTED.filter((x) => x.slug !== a.slug)
  return [...others.filter((x) => x.category === a.category), ...others.filter((x) => x.category !== a.category)].slice(0, count)
}

export interface InlinePart {
  text: string
  to?: string
}

/** розбиває текст з посиланнями [текст](/шлях) на частини — без v-html */
export function parseInline(text: string): InlinePart[] {
  const parts: InlinePart[] = []
  const re = /\[([^\]]+)\]\(([^)\s]+)\)/g
  let last = 0
  for (const m of text.matchAll(re)) {
    if (m.index > last) parts.push({ text: text.slice(last, m.index) })
    parts.push({ text: m[1]!, to: m[2] })
    last = m.index + m[0].length
  }
  if (last < text.length) parts.push({ text: text.slice(last) })
  return parts
}

/** текст без розмітки посилань — для meta та JSON-LD */
export const plainText = (text: string) => parseInline(text).map((p) => p.text).join('')
